const FURI_ENTRIES=Object.entries(FURIGANA).sort((a,b)=>b[0].length-a[0].length);

function withFurigana(value){
  const protectedParts=[];
  const source=String(value).replace(
    /\[\[([\s\S]*?)\]\]/g,
    (_,raw)=>`\uE000${protectedParts.push(raw)-1}\uE001`
  );

  let html='';

  for(let i=0;i<source.length;){
    if(source[i]==='<'){
      const end=source.indexOf('>',i);
      if(end!==-1){
        html+=source.slice(i,end+1);
        i=end+1;
        continue;
      }
    }

    const match=FURI_ENTRIES.find(([word])=>source.startsWith(word,i));

    if(match){
      html+=`<ruby>${match[0]}<rt>${match[1]}</rt></ruby>`;
      i+=match[0].length;
      continue;
    }

    html+=source[i++];
  }

  return html.replace(
    /\uE000(\d+)\uE001/g,
    (_,index)=>`<span class="no-furigana">${protectedParts[Number(index)]}</span>`
  );
}

