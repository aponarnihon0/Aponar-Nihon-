function samePos(w){
  return WORDS.filter(x=>x.pos===w.pos&&x.k!==w.k);
}

function vocab(test){
  const out=[];
  const kanji=WORDS.filter(w=>/[一-龯]/.test(w.k));

  for(let i=0;i<7;i++){
    const w=kanji[((test-1)*7+i)%kanji.length];

    out.push(mk(
      `n5t${test}vkr${i}`,
      w.ex.replace('__',`<u>[[${w.k}]]</u>`),
      w.r,
      shuffled(samePos(w),`kr${test}${i}`).slice(0,3).map(x=>x.r),
      `${w.k}（${w.r}） মানে ${w.bn}।`
    ));
  }

  for(let i=0;i<6;i++){
    const w=kanji[(19+(test-1)*6+i)%kanji.length];

    out.push(mk(
      `n5t${test}vko${i}`,
      w.ex.replace('__',`<u>${w.r}</u>`),
      `[[${w.k}]]`,
      shuffled(
        samePos(w).filter(x=>/[一-龯]/.test(x.k)),
        `ko${test}${i}`
      ).slice(0,3).map(x=>`[[${x.k}]]`),
      `সঠিক লেখা ${w.k}; পড়া ${w.r}, অর্থ ${w.bn}।`
    ));
  }

  for(let i=0;i<7;i++){
    const w=WORDS[(11+(test-1)*7+i)%WORDS.length];

    out.push(mk(
      `n5t${test}vct${i}`,
      w.ex.replace('__','＿＿'),
      w.k,
      shuffled(samePos(w),`ct${test}${i}`).slice(0,3).map(x=>x.k),
      `এখানে ${w.k}（${w.r}） বসবে। অর্থ: ${w.bn}।`
    ));
  }

  for(let i=0;i<5;i++){
    const w=WORDS[(37+(test-1)*5+i)%WORDS.length];

    out.push(mk(
      `n5t${test}vpp${i}`,
      `「${w.k}」と同じ意味はどれですか。`,
      w.syn,
      shuffled(samePos(w),`pp${test}${i}`).slice(0,3).map(x=>x.syn),
      `${w.k}（${w.r}） = ${w.syn}। বাংলা: ${w.bn}।`
    ));
  }

  return out;
}

